import type { EduProgramCategory, EducationProgramItem } from '../types/career';

interface RawProgramRow {
  code: string;
  title: string;
  subject1: string;
  subject2: string;
}

type ProgramDomain = Exclude<EduProgramCategory, 'Барлығы'>;

function normalizePair(s1: string, s2: string): string {
  if (s1 === 'Шығармашылық емтихан' && s2 === 'Шығармашылық емтихан') {
    return 'Шығармашылық емтихан';
  }
  if (
    (s1 === 'Математика' && s2 === 'Физика') ||
    (s1 === 'Физика' && s2 === 'Математика')
  ) {
    return 'Математика + Физика';
  }
  if (
    (s1 === 'Биология' && s2 === 'Химия') ||
    (s1 === 'Химия' && s2 === 'Биология')
  ) {
    return 'Биология + Химия';
  }
  if (
    (s1 === 'Дүниежүзі тарихы' && s2 === 'География') ||
    (s1 === 'География' && s2 === 'Дүниежүзі тарихы')
  ) {
    return 'Дүниежүзі тарихы + География';
  }
  if (
    (s1 === 'Дүниежүзі тарихы' && s2 === 'Шетел тілі') ||
    (s1 === 'Шетел тілі' && s2 === 'Дүниежүзі тарихы')
  ) {
    return 'Дүниежүзі тарихы + Шетел тілі';
  }
  if (s1.includes('тілі') && s2.includes('әдебиеті')) {
    return 'Тіл және әдебиет';
  }
  return `${s1} + ${s2}`;
}

function resolveProgramCategory(row: RawProgramRow): ProgramDomain {
  const num = Number.parseInt(row.code.replace(/^[A-Z]+/, ''), 10);
  const titleLower = row.title.toLowerCase();

  if (row.code === 'B120' || (num >= 1 && num <= 20)) {
    return 'Білім және педагогика';
  }
  if (
    (num >= 21 && num <= 31) ||
    (num >= 99 && num <= 110) ||
    row.code === 'B042' ||
    row.code === 'B142' ||
    row.code === 'B073'
  ) {
    return 'Өнер, дизайн және медиа';
  }
  if (
    (num >= 32 && num <= 41) ||
    row.code === 'B043' ||
    row.code === 'B134' ||
    row.code === 'B234' ||
    row.code === 'B135' ||
    row.code === 'B140' ||
    row.code === 'B090'
  ) {
    return 'Гуманитарлық және әлеуметтік ғылымдар';
  }
  if (
    (num >= 44 && num <= 49) ||
    row.code === 'B141' ||
    row.code === 'B145' ||
    row.code === 'B096'
  ) {
    return 'Бизнес, басқару және құқық';
  }
  if (
    (num >= 50 && num <= 59) ||
    row.code === 'B157' ||
    row.code === 'B158'
  ) {
    return 'IT, математика және жаратылыстану';
  }
  if (
    (num >= 77 && num <= 83) ||
    row.code === 'B051' ||
    row.code === 'B183' ||
    titleLower.includes('шаруашылығы') ||
    titleLower.includes('жерге орналастыру')
  ) {
    return 'Ауыл шаруашылығы және экология';
  }
  if (
    (num >= 84 && num <= 89) ||
    (num >= 91 && num <= 98) ||
    row.code.startsWith('BM')
  ) {
    return 'Медицина, сервис және қауіпсіздік';
  }
  return 'Инженерия, өндіріс және құрылыс';
}

